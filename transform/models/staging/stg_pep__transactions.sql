{{
  config(
    alias=pep_stream_table_name('transactions'),
    materialized='incremental',
    incremental_strategy='merge',
    on_schema_change='append_new_columns',
    partition_by={'field': 'transaction_date', 'data_type': 'date', 'granularity': 'month'},
    cluster_by=['confirmation_number'],
    pre_hook="{{ pep_delete_blocks('transactions', 'transaction_date') }}",
    tags=['silver', 'pep'],
  )
}}

SELECT
  '{{ var("property_id") }}' AS property_id,
  SAFE.PARSE_DATE('%Y-%m-%d', row_date) AS transaction_date,
  NULLIF(TRIM(transaction_time), '') AS transaction_time,
  NULLIF(TRIM(confirmation_number), '') AS confirmation_number,
  NULLIF(TRIM(guest_name), '') AS guest_name,
  NULLIF(TRIM(first_name), '') AS first_name,
  NULLIF(TRIM(last_name), '') AS last_name,
  NULLIF(TRIM(room_number), '') AS room_number,
  NULLIF(TRIM(folio_number), '') AS folio_number,
  NULLIF(TRIM(transaction_code), '') AS transaction_code,
  NULLIF(TRIM(transaction_description), '') AS transaction_description,
  NULLIF(TRIM(last_4_digits), '') AS last_4_digits,
  NULLIF(TRIM(transaction_type), '') AS transaction_type,
  NULLIF(TRIM(charge_type_category), '') AS charge_type_category,
  NULLIF(TRIM(sub_charge_type_name), '') AS sub_charge_type_name,
  NULLIF(TRIM(outlet_name), '') AS outlet_name,
  {{ pep_number('amount') }} AS amount,
  NULLIF(TRIM(username), '') AS username,
  NULLIF(TRIM(remarks), '') AS remarks,
  NULLIF(TRIM(charge_remarks), '') AS charge_remarks,
  NULLIF(TRIM(transferred_transactions), '') AS transferred_transactions,
  NULLIF(TRIM(pos_check_number), '') AS pos_check_number,
  NULLIF(TRIM(tax_invoice_number), '') AS tax_invoice_number,
  NULLIF(TRIM(fiscal_invoice_number), '') AS fiscal_invoice_number,
  NULLIF(TRIM(reference_external_bill_number), '') AS reference_external_bill_number,
  NULLIF(TRIM(company_name), '') AS company_name,
  NULLIF(TRIM(refund_reason), '') AS refund_reason,
  {{ pep_number('quantity') }} AS quantity,
  {{ pep_int('adults') }} AS adults,
  source_file,
  SAFE_CAST(source_line AS INT64) AS source_line,
  parse_status,
  heal_action,
  _run_id,
  _loaded_at AS _bronze_loaded_at,
  CURRENT_TIMESTAMP() AS _loaded_at
FROM ({{ pep_block_rows('transactions') }})
